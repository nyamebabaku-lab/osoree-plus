// The scripture listener in the app: heard references become cards; only "Show" puts them on screen.
import { chromium } from '/home/BrandsME/projects/efiewura/node_modules/playwright-core/index.mjs';
const b = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1148/chrome-linux/chrome' });
const ctx = await b.newContext({ viewport: { width: 400, height: 860 }, serviceWorkers: 'block' });
await ctx.route('https://inoxsalemgwgrzftamxs.supabase.co/**', (r) => r.abort('internetdisconnected'));
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
let pass = 0, fail = 0; const ok = (n, c, x = '') => { c ? pass++ : fail++; console.log(c ? 'PASS' : 'FAIL', n, x); };
const live = () => page.evaluate(() => JSON.parse(localStorage.getItem('osoree-live') || 'null'));
await page.goto('http://127.0.0.1:4871/'); await page.waitForSelector('text=Old Testament');
ok('listener in the Bible tab', await page.getByRole('button', { name: /Listen for scriptures/ }).isVisible());
const before = JSON.stringify(await live());
await page.evaluate(() => window.osoreeHear('so turn with me to Romans chapter eight verse twenty eight'));
await page.waitForSelector('[aria-label="Heard Romans 8:28"]');
ok('card with the reference and the verse text', await page.getByLabel('Heard Romans 8:28').innerText().then((t) => t.includes('all things work together')));
ok('nothing shown before the operator confirms', JSON.stringify(await live()) === before);
await page.evaluate(() => window.osoreeHear('Romans 8 28'));
await page.waitForTimeout(200);
ok('the same reference is not offered twice', await page.getByLabel('Heard Romans 8:28').count() === 1);
await page.getByLabel('Heard Romans 8:28').getByRole('button', { name: 'Show' }).click();
let s = await live();
ok('Show puts it on screen', s.kind === 'verse' && s.groups[0].ref === 'Romans 8:28', s.groups?.[0]?.ref);
ok('card removed after showing', await page.getByLabel('Heard Romans 8:28').count() === 0);
await page.evaluate(() => window.osoreeHear('and look at verse thirty one'));
await page.waitForSelector('[aria-label="Heard Romans 8:31"]');
ok('"verse 31" follows the chapter on screen', true);
await page.evaluate(() => window.osoreeHear('John said to them and the 3 disciples went'));
await page.waitForTimeout(200);
ok('ordinary speech gives no card', await page.locator('[aria-label^="Heard "]').count() === 1);
await page.evaluate(() => window.osoreeHear('first Corinthians thirteen four to seven'));
await page.waitForSelector('[aria-label="Heard 1 Corinthians 13:4-7"]');
await page.getByLabel('Heard 1 Corinthians 13:4-7').getByRole('button', { name: 'Show' }).click();
s = await live();
ok('a range shows all its verses', s.groups[0].ref === '1 Corinthians 13:4-7', s.groups[0].ref);
await page.getByLabel('Heard Romans 8:31').getByRole('button', { name: 'Dismiss' }).click();
ok('cards can be dismissed', await page.locator('[aria-label^="Heard "]').count() === 0);
await page.getByLabel(/Alert sound/).click();
ok('alert sound can be switched off', (await page.evaluate(() => JSON.parse(localStorage.getItem('osoree-plus')).state.listenSound)) === false);
await page.screenshot({ path: 'tests/out/listener.png' });
ok('no page errors', !errs.length, errs.join(' | '));
await b.close();
console.log(`${pass} passed ${fail} failed`);
process.exit(fail ? 1 : 0);
