// The scripture listener's reference spotting (pure logic, with the real KJV for checking that verses exist).
import fs from 'node:fs';
import { findRefs, refName } from '../src/lib/listen.js';
const kjv = JSON.parse(fs.readFileSync('public/bibles/kjv.json', 'utf8'));
let pass = 0, fail = 0;
const t = (said, want, ctx) => { const got = findRefs(said, kjv, ctx).map((r) => refName(r)).join('; '); const ok = got === want; ok ? pass++ : fail++; console.log(ok ? 'PASS' : 'FAIL', JSON.stringify(said), '→', got || '(none)', ok ? '' : `(wanted ${want || 'none'})`); };
t('turn with me to John chapter three verse sixteen', 'John 3:16');
t('the Bible says in John 3:16 for God so loved the world', 'John 3:16');
t('Romans 8 28 and all things work together', 'Romans 8:28');
t('first Corinthians thirteen four to seven', '1 Corinthians 13:4-7');
t('second Timothy chapter two verse fifteen', '2 Timothy 2:15');
t('Psalm twenty three', 'Psalms 23');
t('psalm one hundred and nineteen verse one hundred and five', 'Psalms 119:105');
t('the book of Isaiah chapter fifty three verse five', 'Isaiah 53:5');
t('Song of Solomon two four', 'Song of Solomon 2:4');
t('let us read Acts of the Apostles two verse thirty eight', 'Acts 2:38');
t('Revelations 21 4', 'Revelation 21:4');
t('Genesis 1:1 and John 1:1', 'Genesis 1:1; John 1:1');
t('John said to the people', '');
t('the 3 people went to the market', '');
t('mark my words, in 2 weeks', '');
t('Jude 3', 'Jude 1:3');
t('Psalm 500 verse 2', '');
t('John 3 verse 99', '');
t('look at verse eighteen', 'John 3:18', { b: 42, c: 2 });
t('verses twenty to twenty two', 'John 3:20-22', { b: 42, c: 2 });
t('verse eighteen', '', null);
t('Ephesians 2:8-9', 'Ephesians 2:8-9');
console.log(`${pass} passed ${fail} failed`);
process.exit(fail ? 1 : 0);
