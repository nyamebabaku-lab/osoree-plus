// Copies the projector fonts (latin + latin-ext, one weight each) into public/fonts and writes fonts.css.
// Run after changing the list: node scripts/copy-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';

export const FONTS = [
  ['montserrat', 'Montserrat', 700], ['poppins', 'Poppins', 600], ['open-sans', 'Open Sans', 700], ['noto-sans', 'Noto Sans', 700],
  ['oswald', 'Oswald', 500], ['bebas-neue', 'Bebas Neue', 400], ['merriweather', 'Merriweather', 700], ['lora', 'Lora', 700],
  ['playfair-display', 'Playfair Display', 700], ['roboto-slab', 'Roboto Slab', 700], ['noto-serif', 'Noto Serif', 700], ['dancing-script', 'Dancing Script', 700],
];

const out = 'public/fonts';
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
let css = '/* Generated by scripts/copy-fonts.mjs */\n';
for (const [pkg, family, weight] of FONTS) {
  const dir = `node_modules/@fontsource/${pkg}`;
  const src = fs.readFileSync(`${dir}/${weight}.css`, 'utf8');
  for (const block of src.match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]+}/g) || []) {
    const subset = block.match(/-(latin-ext|latin)-\d+-normal\s*\*\//)?.[1];
    if (!['latin', 'latin-ext'].includes(subset)) continue;
    const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
    fs.copyFileSync(path.join(dir, 'files', file), path.join(out, file));
    const range = block.match(/unicode-range:\s*([^;]+);/)[1];
    css += `@font-face{font-family:'${family}';font-style:normal;font-display:block;font-weight:100 900;src:url(./${file}) format('woff2');unicode-range:${range};}\n`;
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
console.log(fs.readdirSync(out).length - 1, 'font files,', (fs.readdirSync(out).reduce((n, f) => n + fs.statSync(path.join(out, f)).size, 0) / 1e3).toFixed(0), 'KB');
